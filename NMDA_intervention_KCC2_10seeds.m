% LOCAL FUNCTION 1
% DISCHARGE RATE
%% =========================================================

function rate = ...
    calculate_discharge_rate(Vp,dt)

    fs_model = ...
        1000/dt;

    spike_thr = -50;       % mV

    prom_thr = 8;          % mV

    min_dist_sec = 0.12;   % s

    min_dist_samples = ...
        round( ...
        min_dist_sec*fs_model);

    [~,locs] = ...
        findpeaks( ...
        Vp, ...
        'MinPeakHeight', ...
        spike_thr, ...
        'MinPeakProminence', ...
        prom_thr, ...
        'MinPeakDistance', ...
        min_dist_samples);

    durationSec = ...
        length(Vp)/fs_model;

    rate = ...
        length(locs)/durationSec;

end


%% =========================================================
% LOCAL FUNCTION 2
% STATE CLASSIFICATION
%% =========================================================

function [state_id,metrics,debug] = ...
    classify_Vp_state( ...
    Vp, ...
    dt, ...
    t_discard)

    %% ---------------------------------------------
    % Operational thresholds
    %% ---------------------------------------------

    spike_thr = -50;       % mV

    prom_thr = 8;          % mV

    min_dist_sec = 0.12;   % s

    spike_rate_bg = 0.2;   % Hz

    spike_rate_cont = 1.0; % Hz

    max_isi_cont = 3.0;    % s

    bg_p2p_thr = 15;       % mV

    depol_mean_thr = -50;  % mV

    depol_std_thr = 3;     % mV


    %% ---------------------------------------------
    % Sampling frequency
    %% ---------------------------------------------

    fs_original = ...
        1000/dt;


    %% ---------------------------------------------
    % Downsample to approximately 500 Hz
    %% ---------------------------------------------

    ds = ...
        max( ...
        1, ...
        round(fs_original/500));

    x = ...
        Vp(1:ds:end);

    fs = ...
        fs_original/ds;


    %% ---------------------------------------------
    % Discard transient
    %% ---------------------------------------------

    nDiscard = ...
        round(t_discard*fs);

    if nDiscard >= length(x)

        error( ...
            'Discard time is longer than the signal.');

    end

    x = ...
        x(nDiscard+1:end);


    %% ---------------------------------------------
    % Spike detection
    %% ---------------------------------------------

    minDist = ...
        max( ...
        1, ...
        round(min_dist_sec*fs));

    [~,locs] = ...
        findpeaks( ...
        x, ...
        'MinPeakHeight', ...
        spike_thr, ...
        'MinPeakProminence', ...
        prom_thr, ...
        'MinPeakDistance', ...
        minDist);


    %% ---------------------------------------------
    % Basic metrics
    %% ---------------------------------------------

    durationSec = ...
        length(x)/fs;

    nSpikes = ...
        length(locs);

    spikeRate = ...
        nSpikes/durationSec;

    Vp2p = ...
        max(x)-min(x);


    %% ---------------------------------------------
    % Inter-event interval
    %% ---------------------------------------------

    if nSpikes >= 2

        ISI = ...
            diff(locs)/fs;

        maxISI = ...
            max(ISI);

        medianISI = ...
            median(ISI);

    else

        ISI = [];

        maxISI = Inf;

        medianISI = Inf;

    end


    %% ---------------------------------------------
    % Final 20% for plateau/depolarization block
    %% ---------------------------------------------

    nLast = ...
        max( ...
        1, ...
        round(0.20*length(x)));

    xLast = ...
        x(end-nLast+1:end);

    lastMean = ...
        mean(xLast);

    lastStd = ...
        std(xLast);


    %% ---------------------------------------------
    % Classification
    %
    % 1 = Background
    % 2 = Intermittent
    % 3 = Continuous SE-like
    % 4 = Depolarization block-like
    %% ---------------------------------------------

    if ...
        lastMean > depol_mean_thr && ...
        lastStd < depol_std_thr

        state_id = 4;

    elseif ...
        spikeRate < spike_rate_bg && ...
        Vp2p < bg_p2p_thr

        state_id = 1;

    elseif ...
        spikeRate >= spike_rate_cont && ...
        maxISI <= max_isi_cont

        state_id = 3;

    else

        state_id = 2;

    end


    %% ---------------------------------------------
    % Output metrics
    %% ---------------------------------------------

    metrics.spikeRate = ...
        spikeRate;

    metrics.nSpikes = ...
        nSpikes;

    metrics.maxISI = ...
        maxISI;

    metrics.medianISI = ...
        medianISI;

    metrics.Vp2p = ...
        Vp2p;

    metrics.lastMean = ...
        lastMean;

    metrics.lastStd = ...
        lastStd;


    %% ---------------------------------------------
    % Debug information
    %% ---------------------------------------------

    debug.fs = ...
        fs;

    debug.locs = ...
        locs;

    debug.ISI = ...
        ISI;

    debug.signal = ...
        x;

end