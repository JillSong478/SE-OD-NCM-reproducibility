%% =========================================================
% Ketamine-like NMDA intervention at different KCC2 levels
%
% Intervention:
%   before 20 s: WNMDA = 4
%   after  20 s: WNMDA = 2
%
% GABAergic conductance:
%   WGABA = 1 throughout
%
% tau_KCC2:
%   6500, 8000, 10000 ms
%
% Repetitions:
%   10 random seeds for each tau_KCC2
%
% Analysis:
%   pre-treatment  = 10-20 s
%   post-treatment = 30-40 s
%% =========================================================


%% =========================================================
% 1. SETTINGS
%% =========================================================

tau_vals = [6500 8000 10000];   % ms

WGABA = 1;

WNMDA_base  = 4;
WNMDA_treat = 1;

treatTime = 20;       % s

preWindow  = [10 20]; % s
postWindow = [30 40]; % s

dt   = 0.01;          % ms
stop = 45000;         % ms = 45 s

seedList = 1:10;

nSeeds = length(seedList);
nTau   = length(tau_vals);


%% =========================================================
% 2. RESULT VARIABLES
%% =========================================================

Rate_pre_all  = nan(nTau,nSeeds);
Rate_post_all = nan(nTau,nSeeds);

Suppression_all = nan(nTau,nSeeds);

State_pre_all  = nan(nTau,nSeeds);
State_post_all = nan(nTau,nSeeds);

stateNames = { ...
    'Background', ...
    'Intermittent', ...
    'Continuous SE-like', ...
    'Depolarization block-like'};


%% =========================================================
% 3. RUN THREE tau_KCC2 CONDITIONS
%% =========================================================

for ii = 1:nTau

    tau_KCC2 = tau_vals(ii);

    for iseed = 1:nSeeds

        seed = seedList(iseed);

        fprintf('\n');
        fprintf('=============================================\n');
        fprintf('tau_KCC2 = %g ms, seed = %d\n', ...
            tau_KCC2,seed);

        fprintf('WNMDA: %.2f -> %.2f at t = %.1f s\n', ...
            WNMDA_base,WNMDA_treat,treatTime);

        fprintf('=============================================\n');


        %% =================================================
        % MODEL PARAMETERS
        %% =================================================

        Cm = 1;

        taop = 40;
        taoi = 30;
        taot = 20;
        taor = 20;

        Obath = 32;

        Qt_max = 400e-3;
        Qr_max = 400e-3;

        Qp_max = 20e-3;
        Qi_max = 50e-3;

        theta  = -54;
        thetar = -54;

        sigma_p = 4;
        sigma_i = 6;
        sigma_t = 6;
        sigma_r = 4.421;

        gammae = 58e-3;
        gammag = 54e-3;
        gammat = 58e-3;
        gammar = 82e-3;

        gammane = 15e-3;

        v = 120e-3;


        %% Connectivity

        Npp = 130;
        Nip = 80;
        Npi = 95;
        Nii = 90;

        Ntp = 2.3;
        Nrp = 2.3;

        Nrt = 3;
        Ntr = 5;
        Nrr = 25;

        Npt = 2.5;
        Nit = 2.5;


        %% Synaptic parameters

        WAMPA = 1;

        % WGABA remains fixed
        WGABA = 1;

        % WNMDA changes after treatment
        % WNMDA_base  = 4
        % WNMDA_treat = 2


        %% Reversal potentials

        E_L_p = -62;
        E_L_i = -62;
        E_L_t = -70;
        E_L_r = -70;

        P_cl = 0.8;
        P_HCO3 = 1-P_cl;

        E_HCO3 = -18;
        E_Cl0  = -88;

        F_const = 96485;
        R_const = 8.314;
        T_abs   = 310;

        beta_E = ...
            F_const/(R_const*T_abs)*1e-3;

        Cl_o = 135;

        Vol_cell = 1;

        E_Ca_t = 120;
        E_Ca_r = 120;

        EAMPA = 0;
        ENMDA = 0;


        %% Ionic parameters

        alphaNa = 2;
        tao_Na  = 1.7;
        Na0     = 9.5;

        alphaCa = -51.8e-6;
        tao_Ca  = 10;

        Ca0 = 2.4e-4;

        k2 = 4e-4;
        k3 = 1e-1;
        k4 = 1e-3;

        np = 4;
        ginc = 2;


        %% Noise

        phi_C_sd = 80e-3;
        phi_T_sd = 8e-3;

        gammaee = 60e-3;
        gammaei = 60e-3;
        gammaet = 60e-3;


        %% Other membrane parameters

        tao_z_t = 75;

        g_Mr = 1;

        mg = 2;

        % Mg2+-block parameter remains unchanged
        k = 0.8;

        g_L_K_p = 0.042;

        g_Na = 0.032;

        g_K_Na = 1.8;

        g_Mp = 0.8;

        E_CAN = 10;
        g_CAN = 1.2;

        % Type 1 continuous-stage thalamic setting
        g_T_t = 1.9;
        g_T_r = 1.7;

        g_L_K = 0.0251;

        g_h = 0.012;

        E_h = -40;

        k1 = 2.5e7;


        %% =================================================
        % TIME
        %% =================================================

        time_array = 0:dt:stop;

        vec_len = length(time_array);


        %% =================================================
        % INITIALIZE
        %% =================================================

        Vp = zeros(1,vec_len);
        Vi = zeros(1,vec_len);
        Vt = zeros(1,vec_len);
        Vr = zeros(1,vec_len);

        Sep = zeros(1,vec_len);
        Sepdot = zeros(1,vec_len);

        Sei = zeros(1,vec_len);
        Seidot = zeros(1,vec_len);

        Set = zeros(1,vec_len);
        Setdot = zeros(1,vec_len);

        Ser = zeros(1,vec_len);
        Serdot = zeros(1,vec_len);

        Sgp = zeros(1,vec_len);
        Sgpdot = zeros(1,vec_len);

        Sgi = zeros(1,vec_len);
        Sgidot = zeros(1,vec_len);

        Srt = zeros(1,vec_len);
        Srtdot = zeros(1,vec_len);

        Srr = zeros(1,vec_len);
        Srrdot = zeros(1,vec_len);

        phip = zeros(1,vec_len);
        phipdot = zeros(1,vec_len);

        phit = zeros(1,vec_len);
        phitdot = zeros(1,vec_len);

        Nep = zeros(1,vec_len);
        Nepdot = zeros(1,vec_len);

        Nei = zeros(1,vec_len);
        Neidot = zeros(1,vec_len);

        h_T_t = zeros(1,vec_len);
        h_T_r = zeros(1,vec_len);

        m_h1 = zeros(1,vec_len);
        m_h2 = zeros(1,vec_len);

        zp = zeros(1,vec_len);
        zr = zeros(1,vec_len);

        j = zeros(1,vec_len);

        concentration_Ca = zeros(1,vec_len);
        concentration_Na = zeros(1,vec_len);
        concentration_O  = zeros(1,vec_len);
        concentration_K  = zeros(1,vec_len);

        E_Cl = zeros(1,vec_len);

        EGABA_cp = zeros(1,vec_len);
        EGABA_ci = zeros(1,vec_len);
        EGABA    = zeros(1,vec_len);

        I_cl = zeros(1,vec_len);


        %% =================================================
        % INITIAL CONDITIONS
        %% =================================================

        Vp(1) = -64;
        Vi(1) = -64;

        Vt(1) = -70;
        Vr(1) = -70;

        Sep(1) = 0;
        Sepdot(1) = 0;

        Sei(1) = 0;
        Seidot(1) = 0;

        Set(1) = 0;
        Setdot(1) = 0;

        Ser(1) = 0;
        Serdot(1) = 0;

        Sgp(1) = 0;
        Sgpdot(1) = 0;

        Sgi(1) = 0;
        Sgidot(1) = 0;

        Srt(1) = 0;
        Srtdot(1) = 0;

        Srr(1) = 0;
        Srrdot(1) = 0;

        phip(1) = 0;
        phipdot(1) = 0;

        phit(1) = 0;
        phitdot(1) = 0;

        Nep(1) = 0;
        Nepdot(1) = 0;

        Nei(1) = 0;
        Neidot(1) = 0;

        h_T_t(1) = 0;
        h_T_r(1) = 0;

        m_h1(1) = 0;
        m_h2(1) = 0;

        zp(1) = 0;
        zr(1) = 0;

        j(1) = 0;

        concentration_Ca(1) = 2.4e-4;

        concentration_Na(1) = Na0;

        concentration_O(1) = 0.001;

        concentration_K(1) = 4;

        E_Cl(1) = E_Cl0;

        EGABA_cp(1) = ...
            P_cl*E_Cl(1) + ...
            P_HCO3*E_HCO3;

        EGABA_ci(1) = ...
            EGABA_cp(1);

        EGABA(1) = ...
            EGABA_cp(1);

        I_cl(1) = 0;


        %% =================================================
        % RANDOM INPUT
        %
        % Same seed corresponds to the same stochastic
        % realization across the three tau_KCC2 conditions.
        %% =================================================

        rng(seed,'twister');

        noise1 = ...
            gammaee^2 * ...
            sqrt(phi_C_sd*dt) * ...
            randn(1,vec_len);

        noise2 = ...
            gammaei^2 * ...
            sqrt(phi_C_sd*dt) * ...
            randn(1,vec_len);

        noise3 = ...
            gammaet^2 * ...
            sqrt(phi_T_sd*dt) * ...
            randn(1,vec_len);


        %% =================================================
        % INTEGRATION
        %% =================================================

        for t = 2:vec_len


            %% ---------------------------------------------
            % Ketamine-like NMDA intervention
            %% ---------------------------------------------

            currentTime = ...
                (t-1)*dt/1000;   % s

            if currentTime < treatTime

                WNMDA_now = ...
                    WNMDA_base;

            else

                WNMDA_now = ...
                    WNMDA_treat;

            end


            %% ---------------------------------------------
            % Population firing rates
            %% ---------------------------------------------

            C = pi/sqrt(3);

            Qp = ...
                Qp_max / ...
                ( ...
                1 + ...
                exp( ...
                -C*(Vp(t-1)-theta)/sigma_p ...
                ) ...
                );

            Qi = ...
                Qi_max / ...
                ( ...
                1 + ...
                exp( ...
                -C*(Vi(t-1)-theta)/sigma_i ...
                ) ...
                );

            Qt = ...
                Qt_max / ...
                ( ...
                1 + ...
                exp( ...
                -C*(Vt(t-1)-theta)/sigma_t ...
                ) ...
                );

            Qr = ...
                Qr_max / ...
                ( ...
                1 + ...
                exp( ...
                -C*(Vr(t-1)-thetar)/sigma_r ...
                ) ...
                );


            %% ---------------------------------------------
            % NMDA Mg2+ block
            %
            % k remains fixed at 0.8
            %% ---------------------------------------------

            Mp = ...
                1 / ...
                ( ...
                1 + ...
                k * ...
                ( ...
                mg/3.57 * ...
                exp(-0.062*Vp(t-1)) ...
                ) ...
                );

            Mi = ...
                1 / ...
                ( ...
                1 + ...
                k * ...
                ( ...
                mg/3.57 * ...
                exp(-0.062*Vi(t-1)) ...
                ) ...
                );


            %% ---------------------------------------------
            % Leak currents
            %% ---------------------------------------------

            J_L_p = ...
                Vp(t-1)-E_L_p;

            J_L_i = ...
                Vi(t-1)-E_L_i;

            J_L_t = ...
                Vt(t-1)-E_L_t;

            J_L_r = ...
                Vr(t-1)-E_L_r;


            %% ---------------------------------------------
            % AMPA currents
            %% ---------------------------------------------

            JAMPA_Sep = ...
                WAMPA * ...
                Sep(t-1) * ...
                (Vp(t-1)-EAMPA);

            JAMPA_Sei = ...
                WAMPA * ...
                Sei(t-1) * ...
                (Vi(t-1)-EAMPA);

            JAMPA_Set = ...
                WAMPA * ...
                Set(t-1) * ...
                (Vt(t-1)-EAMPA);

            JAMPA_Ser = ...
                WAMPA * ...
                Ser(t-1) * ...
                (Vr(t-1)-EAMPA);


            %% ---------------------------------------------
            % Dynamic GABA reversal potential
            %% ---------------------------------------------

            EGABA_cp(t-1) = ...
                P_cl*E_Cl(t-1) + ...
                P_HCO3*E_HCO3;

            EGABA_ci(t-1) = ...
                P_cl*E_Cl(t-1) + ...
                P_HCO3*E_HCO3;

            EGABA(t-1) = ...
                P_cl*E_Cl(t-1) + ...
                P_HCO3*E_HCO3;


            %% ---------------------------------------------
            % GABA currents
            %
            % WGABA remains fixed at 1
            %% ---------------------------------------------

            JGABA_Sgp = ...
                WGABA * ...
                Sgp(t-1) * ...
                (Vp(t-1)-EGABA_cp(t-1));

            JGABA_Sgi = ...
                WGABA * ...
                Sgi(t-1) * ...
                (Vi(t-1)-EGABA_ci(t-1));

            JGABA_Srt = ...
                WGABA * ...
                Srt(t-1) * ...
                (Vt(t-1)-EGABA(t-1));

            JGABA_Srr = ...
                WGABA * ...
                Srr(t-1) * ...
                (Vr(t-1)-EGABA(t-1));


            %% ---------------------------------------------
            % NMDA currents
            %
            % WNMDA is reduced after t = 20 s
            %% ---------------------------------------------

            JNMDA_Nep = ...
                WNMDA_now * ...
                Nep(t-1) * ...
                Mp * ...
                (Vp(t-1)-ENMDA);

            JNMDA_Nei = ...
                WNMDA_now * ...
                Nei(t-1) * ...
                Mi * ...
                (Vi(t-1)-ENMDA);


            %% ---------------------------------------------
            % Channel gating
            %% ---------------------------------------------

            m_limit_t = ...
                1 / ...
                (1+exp(-(Vt(t-1)+59)/6.2));

            m_limit_r = ...
                1 / ...
                (1+exp(-(Vr(t-1)+52)/7.4));

            h_limit_t = ...
                1 / ...
                (1+exp((Vt(t-1)+81)/4));

            h_limit_r = ...
                1 / ...
                (1+exp((Vr(t-1)+80)/5));

            zp_limit_t = ...
                1 / ...
                (1+exp(-(Vp(t-1)+39)/5));

            zr_limit_t = ...
                1 / ...
                (1+exp(-(Vr(t-1)+39)/5));

            j_limit = ...
                1 / ...
                (1+exp(-(Vr(t-1)+43)/5.2));

            mNa_limit_p = ...
                1 / ...
                (1+exp(-(Vp(t-1)+47)/3));


            %% ---------------------------------------------
            % Na / K reversal potentials
            %% ---------------------------------------------

            E_Na_now = ...
                26.64 * ...
                log( ...
                ( ...
                144 - ...
                7*(concentration_Na(t-1)-18) ...
                ) / ...
                concentration_Na(t-1) ...
                );

            E_K_now = ...
                26.64 * ...
                log( ...
                concentration_K(t-1) / ...
                ( ...
                140 + 18 - ...
                concentration_Na(t-1) ...
                ) ...
                );


            %% ---------------------------------------------
            % Intrinsic currents
            %% ---------------------------------------------

            I_LK_t = ...
                g_L_K * ...
                (Vt(t-1)-E_K_now);

            I_LK_r = ...
                g_L_K * ...
                (Vr(t-1)-E_K_now);

            I_T_t = ...
                g_T_t * ...
                m_limit_t^2 * ...
                h_T_t(t-1) * ...
                (Vt(t-1)-E_Ca_t);

            I_T_r = ...
                g_T_r * ...
                m_limit_r^2 * ...
                h_T_r(t-1) * ...
                (Vr(t-1)-E_Ca_r);

            I_h = ...
                g_h * ...
                ( ...
                m_h1(t-1) + ...
                ginc*m_h2(t-1) ...
                ) * ...
                (Vt(t-1)-E_h);

            I_K_Na = ...
                g_K_Na * ...
                ( ...
                0.37 / ...
                ( ...
                1 + ...
                ( ...
                38.7 / ...
                concentration_Na(t-1) ...
                )^3.5 ...
                ) ...
                ) * ...
                (Vp(t-1)-E_K_now);

            I_M_p = ...
                g_Mp * ...
                zp(t-1) * ...
                (Vp(t-1)-E_K_now);

            I_M_r = ...
                g_Mr * ...
                zr(t-1) * ...
                (Vr(t-1)-E_K_now);

            I_CAN = ...
                g_CAN * ...
                ( ...
                concentration_Ca(t-1) / ...
                (0.2+concentration_Ca(t-1)) ...
                ) * ...
                j(t-1) * ...
                (Vr(t-1)-E_CAN);

            I_Nap_p = ...
                g_Na * ...
                mNa_limit_p * ...
                (Vp(t-1)-E_Na_now);


            %% ---------------------------------------------
            % Time constants
            %% ---------------------------------------------

            tao_j = ...
                1.6 + ...
                2.7 / ...
                ( ...
                exp(-(Vr(t-1)+55)/15) + ...
                exp((Vr(t-1)+55)/15) ...
                );

            tao_h_t = ...
                ( ...
                30.8 + ...
                ( ...
                211.4 + ...
                exp((Vt(t-1)+115.2)/5) ...
                ) / ...
                ( ...
                1 + ...
                exp((Vt(t-1)+86)/3.2) ...
                ) ...
                ) / ...
                3.7371928;

            tao_h_r = ...
                ( ...
                85 + ...
                1 / ...
                ( ...
                exp((Vr(t-1)+48)/4) + ...
                exp(-(Vr(t-1)+407)/50) ...
                ) ...
                ) / ...
                3.7371928;

            m_limit_h = ...
                1 / ...
                ( ...
                1 + ...
                exp((Vt(t-1)+75)/5.5) ...
                );

            tao_m_h = ...
                20 + ...
                1000 / ...
                ( ...
                exp((Vt(t-1)+71.5)/14.2) + ...
                exp(-(Vt(t-1)+89)/11.6) ...
                );

            Ph = ...
                k1 * ...
                concentration_Ca(t-1)^np / ...
                ( ...
                k1*concentration_Ca(t-1)^np + ...
                k2 ...
                );


            %% ---------------------------------------------
            % Pump and metabolic dynamics
            %% ---------------------------------------------

            R_pump = ...
                1.25 / ...
                ( ...
                1 + ...
                exp((20-concentration_O(t-1))/3) ...
                ) * ...
                1 / ...
                ( ...
                1 + ...
                exp((25-concentration_Na(t-1))/3) ...
                ) * ...
                1 / ...
                ( ...
                1 + ...
                exp(5.5-concentration_K(t-1)) ...
                );

            Na_pump = ...
                R_pump * ...
                ( ...
                concentration_Na(t-1)^3 / ...
                ( ...
                concentration_Na(t-1)^3 + ...
                3375 ...
                ) ...
                - ...
                Na0^3 / ...
                (Na0^3+3375) ...
                );


            %% ---------------------------------------------
            % Membrane potentials
            %% ---------------------------------------------

            Vp(t) = ...
                Vp(t-1) + ...
                dt * ...
                ( ...
                -J_L_p ...
                -JAMPA_Sep ...
                -JNMDA_Nep ...
                -JGABA_Sgp ...
                -Cm*taop*(I_M_p+I_Nap_p) ...
                ) / ...
                taop;

            Vi(t) = ...
                Vi(t-1) + ...
                dt * ...
                ( ...
                -J_L_i ...
                -JAMPA_Sei ...
                -JNMDA_Nei ...
                -JGABA_Sgi ...
                ) / ...
                taoi;

            Vt(t) = ...
                Vt(t-1) + ...
                dt * ...
                ( ...
                -J_L_t ...
                -JAMPA_Set ...
                -JGABA_Srt ...
                -Cm*taot*( ...
                I_LK_t + ...
                I_T_t + ...
                I_h ...
                ) ...
                ) / ...
                taot;

            Vr(t) = ...
                Vr(t-1) + ...
                dt * ...
                ( ...
                -J_L_r ...
                -JAMPA_Ser ...
                -JGABA_Srr ...
                -Cm*taor*( ...
                I_LK_r + ...
                I_T_r ...
                ) ...
                ) / ...
                taor;


            %% ---------------------------------------------
            % AMPA synaptic dynamics
            %% ---------------------------------------------

            Sep(t) = ...
                Sep(t-1) + ...
                Sepdot(t-1)*dt;

            Sepdot(t) = ...
                Sepdot(t-1) + ...
                dt * ...
                ( ...
                gammae^2 * ...
                ( ...
                Npp*Qp + ...
                Npt*phit(t-1) - ...
                Sep(t-1) ...
                ) ...
                - ...
                2*gammae*Sepdot(t-1) ...
                ) ...
                + ...
                noise1(t-1);

            Sei(t) = ...
                Sei(t-1) + ...
                Seidot(t-1)*dt;

            Seidot(t) = ...
                Seidot(t-1) + ...
                dt * ...
                ( ...
                gammae^2 * ...
                ( ...
                Nip*Qp + ...
                Nit*phit(t-1) - ...
                Sei(t-1) ...
                ) ...
                - ...
                2*gammae*Seidot(t-1) ...
                ) ...
                + ...
                noise2(t-1);

            Set(t) = ...
                Set(t-1) + ...
                Setdot(t-1)*dt;

            Setdot(t) = ...
                Setdot(t-1) + ...
                dt * ...
                ( ...
                gammat^2 * ...
                ( ...
                Ntp*phip(t-1) - ...
                Set(t-1) ...
                ) ...
                - ...
                2*gammat*Setdot(t-1) ...
                ) ...
                + ...
                noise3(t-1);

            Ser(t) = ...
                Ser(t-1) + ...
                Serdot(t-1)*dt;

            Serdot(t) = ...
                Serdot(t-1) + ...
                dt * ...
                ( ...
                gammat^2 * ...
                ( ...
                Nrt*Qt + ...
                Nrp*phip(t-1) - ...
                Ser(t-1) ...
                ) ...
                - ...
                2*gammat*Serdot(t-1) ...
                );


            %% ---------------------------------------------
            % NMDA synaptic variables
            %% ---------------------------------------------

            Nep(t) = ...
                Nep(t-1) + ...
                Nepdot(t-1)*dt;

            Nepdot(t) = ...
                Nepdot(t-1) + ...
                dt * ...
                ( ...
                gammane^2 * ...
                ( ...
                Npp*Qp - ...
                Nep(t-1) ...
                ) ...
                - ...
                2*gammane*Nepdot(t-1) ...
                );

            Nei(t) = ...
                Nei(t-1) + ...
                Neidot(t-1)*dt;

            Neidot(t) = ...
                Neidot(t-1) + ...
                dt * ...
                ( ...
                gammane^2 * ...
                ( ...
                Nip*Qp - ...
                Nei(t-1) ...
                ) ...
                - ...
                2*gammane*Neidot(t-1) ...
                );


            %% ---------------------------------------------
            % GABA synaptic variables
            %% ---------------------------------------------

            Sgp(t) = ...
                Sgp(t-1) + ...
                Sgpdot(t-1)*dt;

            Sgpdot(t) = ...
                Sgpdot(t-1) + ...
                dt * ...
                ( ...
                gammag^2 * ...
                ( ...
                Npi*Qi - ...
                Sgp(t-1) ...
                ) ...
                - ...
                2*gammag*Sgpdot(t-1) ...
                );

            Sgi(t) = ...
                Sgi(t-1) + ...
                Sgidot(t-1)*dt;

            Sgidot(t) = ...
                Sgidot(t-1) + ...
                dt * ...
                ( ...
                gammag^2 * ...
                ( ...
                Nii*Qi - ...
                Sgi(t-1) ...
                ) ...
                - ...
                2*gammag*Sgidot(t-1) ...
                );

            Srt(t) = ...
                Srt(t-1) + ...
                Srtdot(t-1)*dt;

            Srtdot(t) = ...
                Srtdot(t-1) + ...
                dt * ...
                ( ...
                gammar^2 * ...
                ( ...
                Ntr*Qr - ...
                Srt(t-1) ...
                ) ...
                - ...
                2*gammar*Srtdot(t-1) ...
                );

            Srr(t) = ...
                Srr(t-1) + ...
                Srrdot(t-1)*dt;

            Srrdot(t) = ...
                Srrdot(t-1) + ...
                dt * ...
                ( ...
                gammar^2 * ...
                ( ...
                Nrr*Qr - ...
                Srr(t-1) ...
                ) ...
                - ...
                2*gammar*Srrdot(t-1) ...
                );


            %% ---------------------------------------------
            % Axonal fields
            %% ---------------------------------------------

            phip(t) = ...
                phip(t-1) + ...
                phipdot(t-1)*dt;

            phipdot(t) = ...
                phipdot(t-1) + ...
                dt * ...
                ( ...
                v^2*(Qp-phip(t-1)) ...
                - ...
                2*v*phipdot(t-1) ...
                );

            phit(t) = ...
                phit(t-1) + ...
                phitdot(t-1)*dt;

            phitdot(t) = ...
                phitdot(t-1) + ...
                dt * ...
                ( ...
                v^2*(Qt-phit(t-1)) ...
                - ...
                2*v*phitdot(t-1) ...
                );


            %% ---------------------------------------------
            % Gating dynamics
            %% ---------------------------------------------

            h_T_t(t) = ...
                h_T_t(t-1) + ...
                dt * ...
                ( ...
                h_limit_t-h_T_t(t-1) ...
                ) / ...
                tao_h_t;

            h_T_r(t) = ...
                h_T_r(t-1) + ...
                dt * ...
                ( ...
                h_limit_r-h_T_r(t-1) ...
                ) / ...
                tao_h_r;

            m_h1(t) = ...
                m_h1(t-1) + ...
                dt * ...
                ( ...
                ( ...
                m_limit_h*(1-m_h2(t-1)) ...
                - ...
                m_h1(t-1) ...
                ) / ...
                tao_m_h ...
                - ...
                k3*Ph*m_h1(t-1) ...
                + ...
                k4*m_h2(t-1) ...
                );

            m_h2(t) = ...
                m_h2(t-1) + ...
                dt * ...
                ( ...
                k3*Ph*m_h1(t-1) ...
                - ...
                k4*m_h2(t-1) ...
                );

            zp(t) = ...
                zp(t-1) + ...
                dt * ...
                ( ...
                zp_limit_t-zp(t-1) ...
                ) / ...
                tao_z_t;

            zr(t) = ...
                zr(t-1) + ...
                dt * ...
                ( ...
                zr_limit_t-zr(t-1) ...
                ) / ...
                tao_z_t;

            j(t) = ...
                j(t-1) + ...
                dt * ...
                ( ...
                j_limit ...
                - ...
                j(t-1)/tao_j ...
                );


            %% ---------------------------------------------
            % Ionic dynamics
            %% ---------------------------------------------

            concentration_Ca(t) = ...
                concentration_Ca(t-1) + ...
                dt * ...
                ( ...
                alphaCa*I_T_t ...
                - ...
                ( ...
                concentration_Ca(t-1)-Ca0 ...
                ) / ...
                tao_Ca ...
                );

            concentration_Na(t) = ...
                concentration_Na(t-1) + ...
                dt * ...
                ( ...
                alphaNa*Qp ...
                - ...
                Na_pump ...
                ) / ...
                tao_Na;

            concentration_K(t) = ...
                concentration_K(t-1) + ...
                dt * ...
                ( ...
                0.3115*I_M_p ...
                - ...
                14*R_pump ...
                );

            concentration_O(t) = ...
                concentration_O(t-1) + ...
                dt * ...
                ( ...
                -5.3*R_pump ...
                + ...
                0.17 * ...
                ( ...
                Obath-concentration_O(t-1) ...
                ) ...
                );


            %% ---------------------------------------------
            % Chloride dynamics
            %
            % WGABA remains fixed
            %% ---------------------------------------------

            I_cl(t-1) = ...
                WGABA * ...
                Sgp(t-1) * ...
                P_cl * ...
                ( ...
                Vp(t-1)-E_Cl(t-1) ...
                );

            E_Cl(t) = ...
                E_Cl(t-1) + ...
                dt * ...
                ( ...
                I_cl(t-1) / ...
                ( ...
                beta_E * ...
                exp(beta_E*E_Cl(t-1)) * ...
                F_const * ...
                Vol_cell * ...
                Cl_o ...
                ) ...
                - ...
                ( ...
                E_Cl(t-1)-E_Cl0 ...
                ) / ...
                tau_KCC2 ...
                );

        end


        %% =================================================
        % PRE-TREATMENT WINDOW
        %% =================================================

        idx_pre1 = ...
            round(preWindow(1)*1000/dt)+1;

        idx_pre2 = ...
            round(preWindow(2)*1000/dt)+1;

        Vp_pre = ...
            Vp(idx_pre1:idx_pre2-1);


        %% =================================================
        % POST-TREATMENT WINDOW
        %% =================================================

        idx_post1 = ...
            round(postWindow(1)*1000/dt)+1;

        idx_post2 = ...
            round(postWindow(2)*1000/dt)+1;

        Vp_post = ...
            Vp(idx_post1:idx_post2-1);


        %% =================================================
        % DISCHARGE RATE
        %% =================================================

        Rate_pre_all(ii,iseed) = ...
            calculate_discharge_rate( ...
            Vp_pre,dt);

        Rate_post_all(ii,iseed) = ...
            calculate_discharge_rate( ...
            Vp_post,dt);


        %% =================================================
        % SUPPRESSION
        %% =================================================

        if Rate_pre_all(ii,iseed) > 0

            Suppression_all(ii,iseed) = ...
                100 * ...
                ( ...
                1 - ...
                Rate_post_all(ii,iseed)/ ...
                Rate_pre_all(ii,iseed) ...
                );

        end


        %% =================================================
        % STATE CLASSIFICATION
        %% =================================================

        [State_pre_all(ii,iseed),~,~] = ...
            classify_Vp_state( ...
            Vp_pre,dt,0);

        [State_post_all(ii,iseed),~,~] = ...
            classify_Vp_state( ...
            Vp_post,dt,0);


        %% =================================================
        % PRINT EACH RUN
        %% =================================================

        fprintf( ...
            'Pre-state  : %s\n', ...
            stateNames{State_pre_all(ii,iseed)});

        fprintf( ...
            'Post-state : %s\n', ...
            stateNames{State_post_all(ii,iseed)});

        fprintf( ...
            'Pre rate   = %.3f events/s\n', ...
            Rate_pre_all(ii,iseed));

        fprintf( ...
            'Post rate  = %.3f events/s\n', ...
            Rate_post_all(ii,iseed));

        fprintf( ...
            'Suppression = %.1f %%\n', ...
            Suppression_all(ii,iseed));

    end
end


