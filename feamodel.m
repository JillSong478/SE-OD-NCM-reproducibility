%% =========================================================
%% LOCAL FUNCTION 2
% FEATURE EXTRACTION
%% =========================================================

function R = extract_features( ...
    EEG, ...
    fsOriginal, ...
    fsDet, ...
    kNEO, ...
    T_NEO, ...
    burstGapSec, ...
    minEventsPerBurst, ...
    fsPSD, ...
    freqRange, ...
    deltaRange, ...
    fGrid, ...
    welchWindowSec, ...
    welchOverlap, ...
    nfft)


EEG = ...
    double(EEG(:));


EEG = ...
    detrend(EEG);


EEG = ...
    EEG - mean(EEG);


%% k-NEO

[locs_det,x_det] = ...
    kneo_detect( ...
    EEG, ...
    fsOriginal, ...
    fsDet, ...
    kNEO, ...
    T_NEO);


nEvents = ...
    length(locs_det);


durationSec = ...
    length(x_det) / ...
    fsDet;


R.DischargeRate = ...
    nEvents / ...
    durationSec;


%% IDI

if nEvents >= 2

    IDI = ...
        diff(locs_det) / ...
        fsDet;


    R.MedianIDI = ...
        median(IDI);


    R.MeanIDI = ...
        mean(IDI);

else

    R.MedianIDI = NaN;

    R.MeanIDI = NaN;

end


%% =========================================================
% Burst features
%
% A burst:
% consecutive events separated by <= burstGapSec
% and containing at least minEventsPerBurst events.
%
% BurstEventFraction =
% number of events belonging to valid bursts
% divided by total number of detected events.
%% =========================================================

if nEvents >= minEventsPerBurst

    eventTimes = ...
        locs_det / ...
        fsDet;


    gaps = ...
        diff(eventTimes);


    burstStart = ...
        [ ...
        1; ...
        find(gaps > burstGapSec) + 1 ...
        ];


    burstEnd = ...
        [ ...
        find(gaps > burstGapSec); ...
        nEvents ...
        ];


    burstDuration = [];


    % NEW:
    % total number of events belonging to valid bursts
    nEventsInValidBursts = 0;


    for ib = 1:length(burstStart)

        idxB = ...
            burstStart(ib): ...
            burstEnd(ib);


        if length(idxB) >= ...
                minEventsPerBurst


            tempDur = ...
                eventTimes(idxB(end)) ...
                - ...
                eventTimes(idxB(1));


            burstDuration( ...
                end+1,1) = ...
                tempDur; %#ok<AGROW>


            % NEW:
            % accumulate number of events in valid bursts
            nEventsInValidBursts = ...
                nEventsInValidBursts + ...
                length(idxB);

        end

    end


    if isempty(burstDuration)

        R.MedianBurstDuration = NaN;

        R.BurstEventFraction = 0;

        R.ActiveFraction = 0;


    else

        R.MedianBurstDuration = ...
            median(burstDuration);


        % NEW:
        % fraction of all detected events occurring in bursts
        R.BurstEventFraction = ...
            nEventsInValidBursts / ...
            nEvents;


        R.ActiveFraction = ...
            min( ...
            sum(burstDuration) / ...
            durationSec, ...
            1);

    end


else

    R.MedianBurstDuration = NaN;


    if nEvents > 0

        R.BurstEventFraction = 0;

    else

        R.BurstEventFraction = NaN;

    end


    R.ActiveFraction = 0;

end


%% PSD

if abs(fsOriginal-fsPSD) > 1e-8

    [p,q] = ...
        rat( ...
        fsPSD/fsOriginal);


    x_psd = ...
        resample( ...
        EEG,p,q);

else

    x_psd = EEG;

end


x_psd = ...
    detrend(x_psd);


x_psd = ...
    x_psd - mean(x_psd);


winLength = ...
    round( ...
    welchWindowSec*fsPSD);


overlapLength = ...
    round( ...
    welchOverlap*winLength);


[Pxx,F] = ...
    pwelch( ...
    x_psd, ...
    hamming(winLength), ...
    overlapLength, ...
    nfft, ...
    fsPSD);


idxFreq = ...
    F >= freqRange(1) & ...
    F <= freqRange(2);


F_use = ...
    F(idxFreq);


P_use = ...
    Pxx(idxFreq);


totalPower = ...
    trapz( ...
    F_use,P_use);


if totalPower <= 0 || ...
        ~isfinite(totalPower)

    error('Invalid PSD total power.');

end


P_norm = ...
    P_use / ...
    totalPower;


%% Dominant frequency

[~,idxPeak] = ...
    max(P_norm);


R.DominantFreq = ...
    F_use(idxPeak);


%% Delta relative power

idxDelta = ...
    F_use >= deltaRange(1) & ...
    F_use <= deltaRange(2);


R.DeltaRelativePower = ...
    trapz( ...
    F_use(idxDelta), ...
    P_norm(idxDelta));


%% Interpolate

P_grid = ...
    interp1( ...
    F_use, ...
    P_norm, ...
    fGrid, ...
    'linear', ...
    NaN);


good = ...
    isfinite(P_grid);


areaGrid = ...
    trapz( ...
    fGrid(good), ...
    P_grid(good));


if areaGrid > 0

    P_grid(good) = ...
        P_grid(good) / ...
        areaGrid;

end


R.PSD = ...
    P_grid;

end


%% =========================================================
%% LOCAL FUNCTION 3
% k-NEO DETECTOR
%% =========================================================

function [locs_det,x_det] = ...
    kneo_detect( ...
    x, ...
    fsOriginal, ...
    fsDet, ...
    kNEO, ...
    threshold)


if abs(fsOriginal-fsDet) > 1e-8

    [p,q] = ...
        rat(fsDet/fsOriginal);


    x_det = ...
        resample(x,p,q);

else

    x_det = x;

end


x_det = ...
    double(x_det(:));


x_det = ...
    detrend(x_det);


x_det = ...
    x_det - ...
    mean(x_det);


sigma_x = ...
    std(x_det);


if sigma_x <= 0 || ...
        ~isfinite(sigma_x)

    locs_det = [];

    return;

end


x_norm = ...
    x_det / ...
    sigma_x;


N = ...
    length(x_norm);


neo = ...
    zeros(N,1);


idx = ...
    (kNEO+1):(N-kNEO);


neo(idx) = ...
    x_norm(idx).^2 ...
    - ...
    x_norm(idx-kNEO).* ...
    x_norm(idx+kNEO);


winLength = ...
    4*kNEO + 1;


w = ...
    hamming(winLength);


w = ...
    w / sum(w);


neo_smooth = ...
    conv( ...
    neo,w,'same');


mask = ...
    neo_smooth > ...
    threshold;


dmask = ...
    diff( ...
    [false;mask;false]);


eventStart = ...
    find(dmask==1);


eventEnd = ...
    find(dmask==-1)-1;


nEvents = ...
    length(eventStart);


locs_det = ...
    zeros(nEvents,1);


for ie = 1:nEvents

    currentRange = ...
        eventStart(ie): ...
        eventEnd(ie);


    [~,localMax] = ...
        max( ...
        neo_smooth(currentRange));


    locs_det(ie) = ...
        currentRange(localMax);

end

end


%% =========================================================
%% LOCAL FUNCTION 4
% LINEAR PSD -> RELATIVE dB
%
% Each individual spectrum gets its own 0-dB peak.
%% =========================================================

function P_rel_dB = relative_dB(P)


P = ...
    double(P);


P_rel_dB = ...
    nan(size(P));


good = ...
    isfinite(P) & ...
    P >= 0;


if ~any(good)

    return;

end


Pmax = ...
    max(P(good));


if Pmax <= 0

    return;

end


% Numerical floor = 120 dB below peak

floorValue = ...
    Pmax * 1e-12;


P_safe = P;


P_safe(good) = ...
    max( ...
    P(good), ...
    floorValue);


P_rel_dB(good) = ...
    10*log10( ...
    P_safe(good));


% Each individual PSD:
% maximum = 0 dB

P_rel_dB(good) = ...
    P_rel_dB(good) ...
    - ...
    max(P_rel_dB(good));

end