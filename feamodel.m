%% =========================================================
% CONTINUOUS-SE MODEL VALIDATION
%
% 25 stochastic simulations
% + temporal features
% + normalized linear PSD
% + relative-dB spectral-shape comparison
%
% IMPORTANT:
% Relative-dB analysis is performed as:
%
%   each PSD -> relative dB -> average across realizations/animals
%
% NOT:
%
%   average PSD -> relative dB
%
%% =========================================================


%% =========================================================
% 1. MODEL TYPE
%
% Change only this line:
% 'Type1' / 'Type3' / 'Type4'
%% =========================================================

modelType = 'Type4';

switch modelType

    case 'Type1'

        tau_KCC2_model = 8000;
        k_model        = 0.8;
        g_T_t_model    = 1.9;
        g_T_r_model    = 1.7;

    case 'Type3'

        tau_KCC2_model = 8000;
        k_model        = 0.8;
        g_T_t_model    = 3.1;
        g_T_r_model    = 2.4;

    case 'Type4'

        tau_KCC2_model = 5000;
        k_model        = 0.9;
        g_T_t_model    = 2.7;
        g_T_r_model    = 2.5;

    otherwise

        error('Unknown modelType.');

end


% Other continuous-stage parameters
g_Na_model = 0.032;
g_Mp_model = 0.8;

% For electrophysiological validation
Obath_model = 32;


%% =========================================================
% 2. NUMBER OF SIMULATIONS
%% =========================================================

nRuns = 25;

seedList = 1:nRuns;


%% =========================================================
% 3. NUMERICAL SETTINGS
%% =========================================================

dt = 0.01;               % ms

transientTime = 10;      % s

analysisTime  = 30;      % s

totalTime = ...
    transientTime + analysisTime;

stop = ...
    totalTime * 1000;    % ms


%% =========================================================
% 4. FEATURE EXTRACTION SETTINGS
%% =========================================================

% k-NEO
fsDet = 256;
kNEO  = 3;
T_NEO = 1.8;

% Burst definition
burstGapSec = 0.5;
minEventsPerBurst = 3;

% PSD
fsPSD = 1000;

freqRange = [1 30];

deltaRange = [1 4];

fGrid = 1:0.1:30;

welchWindowSec = 4;

welchOverlap = 0.5;

nfft = 10000;


%% =========================================================
% 5. EXPERIMENTAL PSD FILE
%% =========================================================

expPSDFile = ...
'D:\Pilocarpine\Pilocarpine\Pilocarpine - GFP\Extracted_30s\Feature_results_kNEO\Experimental_continuous_kNEO_PSD.mat';


%% =========================================================
% 6. OUTPUT FOLDER
%% =========================================================

outFolder = ...
'D:\Pilocarpine\Pilocarpine\Pilocarpine - GFP\Model_validation_25runs';

if ~exist(outFolder,'dir')

    mkdir(outFolder);

end


%% =========================================================
% 7. INITIALIZE MODEL RESULTS
%% =========================================================

DischargeRate = nan(nRuns,1);

MedianIDI = nan(nRuns,1);

MeanIDI = nan(nRuns,1);

MedianBurstDuration = nan(nRuns,1);

% NEW:
% Fraction of detected events belonging to valid bursts
BurstEventFraction = nan(nRuns,1);

ActiveFraction = nan(nRuns,1);

DominantFreq = nan(nRuns,1);

DeltaRelativePower = nan(nRuns,1);

PSD_model_all = ...
    nan(nRuns,length(fGrid));


%% =========================================================
% 8. RUN MODEL 25 TIMES
%% =========================================================

fprintf('\n');

fprintf('=============================================\n');

fprintf('%s continuous-SE simulations\n',modelType);

fprintf('n = %d\n',nRuns);

fprintf( ...
    'tau_KCC2 = %g ms, k = %.2f\n', ...
    tau_KCC2_model, ...
    k_model);

fprintf( ...
    'g_T_t = %.2f, g_T_r = %.2f\n', ...
    g_T_t_model, ...
    g_T_r_model);

fprintf('=============================================\n');


for irun = 1:nRuns

    seed = seedList(irun);

    fprintf( ...
        'Run %02d / %02d, seed = %d\n', ...
        irun, ...
        nRuns, ...
        seed);


    %% -----------------------------------------------------
    % Model simulation
    %% -----------------------------------------------------

    Vp = simulate_SE_model( ...
        seed, ...
        dt, ...
        stop, ...
        tau_KCC2_model, ...
        k_model, ...
        g_Na_model, ...
        g_Mp_model, ...
        g_T_t_model, ...
        g_T_r_model, ...
        Obath_model);


    %% -----------------------------------------------------
    % Remove first 10 s
    %% -----------------------------------------------------

    idx_start = ...
        round( ...
        transientTime*1000/dt) + 1;

    idx_end = ...
        round( ...
        (transientTime+analysisTime)*1000/dt) + 1;


    EEG = ...
        -Vp(idx_start:idx_end);


    % Remove endpoint
    EEG = ...
        EEG(1:end-1);


    fs_model = ...
        1000/dt;


    %% -----------------------------------------------------
    % Feature extraction
    %% -----------------------------------------------------

    R = extract_features( ...
        EEG, ...
        fs_model, ...
        fsDet, ...
        kNEO, ...
        T_NEO, ...
        burstGapSec, ...
        minEventsPerBurst, ...
        fsPSD, ...
        freqRange, ...
        deltaRange, ...
        fGrid, ...
        welchWindowSec, ...
        welchOverlap, ...
        nfft);


    %% -----------------------------------------------------
    % Save features
    %% -----------------------------------------------------

    DischargeRate(irun) = ...
        R.DischargeRate;


    MedianIDI(irun) = ...
        R.MedianIDI;


    MeanIDI(irun) = ...
        R.MeanIDI;


    MedianBurstDuration(irun) = ...
        R.MedianBurstDuration;


    % NEW
    BurstEventFraction(irun) = ...
        R.BurstEventFraction;


    ActiveFraction(irun) = ...
        R.ActiveFraction;


    DominantFreq(irun) = ...
        R.DominantFreq;


    DeltaRelativePower(irun) = ...
        R.DeltaRelativePower;


    PSD_model_all(irun,:) = ...
        R.PSD;


    fprintf( ...
        ['  rate = %.3f/s, IDI = %.3f s, ' ...
         'burst = %.3f s, events in bursts = %.1f%%, ' ...
         'fpeak = %.2f Hz, delta = %.3f\n'], ...
        R.DischargeRate, ...
        R.MedianIDI, ...
        R.MedianBurstDuration, ...
        100*R.BurstEventFraction, ...
        R.DominantFreq, ...
        R.DeltaRelativePower);

end


