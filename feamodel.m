%% =========================================================
% 15. INTERPOLATE EACH EXPERIMENTAL PSD
%% =========================================================

PSD_exp_interp = ...
    nan( ...
    nAnimals, ...
    length(fGrid));


for ia = 1:nAnimals

    temp = ...
        interp1( ...
        fGrid_exp, ...
        PSD_exp_all(ia,:), ...
        fGrid, ...
        'linear', ...
        NaN);


    good = ...
        isfinite(temp) & ...
        temp >= 0;


    if sum(good) >= 2

        areaExp = ...
            trapz( ...
            fGrid(good), ...
            temp(good));


        if areaExp > 0

            temp(good) = ...
                temp(good) / ...
                areaExp;

        end

    end


    PSD_exp_interp(ia,:) = ...
        temp;

end


