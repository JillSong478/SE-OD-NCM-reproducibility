%% =========================================================
%% LOCAL FUNCTION 1
% SIMULATE ONE MODEL REALIZATION
%% =========================================================

function Vp_trace = simulate_SE_model( ...
    seed, ...
    dt, ...
    stop, ...
    tau_KCC2, ...
    k, ...
    g_Na, ...
    g_Mp, ...
    g_T_t, ...
    g_T_r, ...
    Obath)


rng(seed,'twister');


%% Model parameters

Cm = 1;

taop = 40;
taoi = 30;
taot = 20;
taor = 20;

Qt_max = 400e-3;
Qr_max = 400e-3;
Qp_max = 20e-3;
Qi_max = 50e-3;

theta = -54;
thetar = -54;

sigma_p = 4;
sigma_i = 6;
sigma_t = 6;
sigma_r = 4.421;

gammae = 58e-3;
gammag = 54e-3;
gammat = 58e-3;
gammar = 82e-3;
gammane = 15e-3;

v = 120e-3;

Npp = 130;
Nip = 80;
Npi = 95;
Nii = 90;

Ntp = 2.3;
Nrp = 2.3;
Nrt = 3;
Ntr = 5;
Nrr = 25;

Npt = 2.5;
Nit = 2.5;

WAMPA = 1;
WGABA = 1;
WNMDA = 4;

E_L_p = -62;
E_L_i = -62;
E_L_t = -70;
E_L_r = -70;

P_cl = 0.8;

P_HCO3 = ...
    1-P_cl;

E_HCO3 = -18;
E_Cl0 = -88;

F_const = 96485;
R_const = 8.314;
T_abs = 310;

beta_E = ...
    F_const / ...
    (R_const*T_abs) * ...
    1e-3;

Cl_o = 135;

Vol_cell = 1;

E_Ca_t = 120;
E_Ca_r = 120;

EAMPA = 0;
ENMDA = 0;

alphaNa = 2;
tao_Na = 1.7;

Na0 = 9.5;

alphaCa = -51.8e-6;
tao_Ca = 10;

Ca0 = 2.4e-4;

k2 = 4e-4;
k3 = 1e-1;
k4 = 1e-3;

np = 4;

ginc = 2;

phi_C_sd = 80e-3;
phi_T_sd = 8e-3;

gammaee = 60e-3;
gammaei = 60e-3;
gammaet = 60e-3;

tao_z_t = 75;

mg = 2;

g_L_K = 0.0251;

g_h = 0.012;

E_h = -40;

k1 = 2.5e7;


%% Time

time_array = ...
    0:dt:stop;

vec_len = ...
    length(time_array);


%% Initial conditions

Vp = -64;
Vi = -64;
Vt = -70;
Vr = -70;

Sep = 0;
Sepdot = 0;

Sei = 0;
Seidot = 0;

Set = 0;
Setdot = 0;

Ser = 0;
Serdot = 0;

Sgp = 0;
Sgpdot = 0;

Sgi = 0;
Sgidot = 0;

Srt = 0;
Srtdot = 0;

Srr = 0;
Srrdot = 0;

phip = 0;
phipdot = 0;

phit = 0;
phitdot = 0;

Nep = 0;
Nepdot = 0;

Nei = 0;
Neidot = 0;

h_T_t = 0;
h_T_r = 0;

m_h1 = 0;
m_h2 = 0;

zp = 0;
zr = 0;

j = 0;

concentration_Ca = 2.4e-4;

concentration_Na = Na0;

concentration_O = 0.001;

concentration_K = 4;

E_Cl = E_Cl0;


Vp_trace = ...
    zeros(1,vec_len);

Vp_trace(1) = Vp;


%% Noise

noise1 = ...
    gammaee^2 * ...
    sqrt(phi_C_sd*dt) * ...
    randn(1,vec_len);

noise2 = ...
    gammaei^2 * ...
    sqrt(phi_C_sd*dt) * ...
    randn(1,vec_len);

noise3 = ...
    gammaet^2 * ...
    sqrt(phi_T_sd*dt) * ...
    randn(1,vec_len);


%% =========================================================
% Integration
%% =========================================================

for t = 2:vec_len

    C = ...
        pi/sqrt(3);


    Qp = ...
        Qp_max / ...
        (1 + exp(-C*(Vp-theta)/sigma_p));


    Qi = ...
        Qi_max / ...
        (1 + exp(-C*(Vi-theta)/sigma_i));


    Qt = ...
        Qt_max / ...
        (1 + exp(-C*(Vt-theta)/sigma_t));


    Qr = ...
        Qr_max / ...
        (1 + exp(-C*(Vr-thetar)/sigma_r));


    Mp = ...
        1 / ...
        ( ...
        1 + ...
        k*(mg/3.57*exp(-0.062*Vp)) ...
        );


    Mi = ...
        1 / ...
        ( ...
        1 + ...
        k*(mg/3.57*exp(-0.062*Vi)) ...
        );


    J_L_p = Vp-E_L_p;
    J_L_i = Vi-E_L_i;
    J_L_t = Vt-E_L_t;
    J_L_r = Vr-E_L_r;


    JAMPA_Sep = ...
        WAMPA*Sep*(Vp-EAMPA);

    JAMPA_Sei = ...
        WAMPA*Sei*(Vi-EAMPA);

    JAMPA_Set = ...
        WAMPA*Set*(Vt-EAMPA);

    JAMPA_Ser = ...
        WAMPA*Ser*(Vr-EAMPA);


    EGABA_cp = ...
        P_cl*E_Cl + ...
        P_HCO3*E_HCO3;

    EGABA_ci = EGABA_cp;
    EGABA = EGABA_cp;


    JGABA_Sgp = ...
        WGABA*Sgp*(Vp-EGABA_cp);

    JGABA_Sgi = ...
        WGABA*Sgi*(Vi-EGABA_ci);

    JGABA_Srt = ...
        WGABA*Srt*(Vt-EGABA);

    JGABA_Srr = ...
        WGABA*Srr*(Vr-EGABA);


    JNMDA_Nep = ...
        WNMDA*Nep*Mp*(Vp-ENMDA);

    JNMDA_Nei = ...
        WNMDA*Nei*Mi*(Vi-ENMDA);


    m_limit_t = ...
        1/(1+exp(-(Vt+59)/6.2));

    m_limit_r = ...
        1/(1+exp(-(Vr+52)/7.4));

    h_limit_t = ...
        1/(1+exp((Vt+81)/4));

    h_limit_r = ...
        1/(1+exp((Vr+80)/5));

    zp_limit_t = ...
        1/(1+exp(-(Vp+39)/5));

    zr_limit_t = ...
        1/(1+exp(-(Vr+39)/5));

    j_limit = ...
        1/(1+exp(-(Vr+43)/5.2));

    mNa_limit_p = ...
        1/(1+exp(-(Vp+47)/3));


    E_Na = ...
        26.64 * ...
        log( ...
        (144-7*(concentration_Na-18)) / ...
        concentration_Na ...
        );


    E_K = ...
        26.64 * ...
        log( ...
        concentration_K / ...
        (140+18-concentration_Na) ...
        );


    I_LK_t = ...
        g_L_K*(Vt-E_K);

    I_LK_r = ...
        g_L_K*(Vr-E_K);


    I_T_t = ...
        g_T_t * ...
        m_limit_t^2 * ...
        h_T_t * ...
        (Vt-E_Ca_t);


    I_T_r = ...
        g_T_r * ...
        m_limit_r^2 * ...
        h_T_r * ...
        (Vr-E_Ca_r);


    I_h = ...
        g_h * ...
        (m_h1+ginc*m_h2) * ...
        (Vt-E_h);


    I_M_p = ...
        g_Mp*zp*(Vp-E_K);


    I_Nap_p = ...
        g_Na*mNa_limit_p*(Vp-E_Na);


    tao_j = ...
        1.6 + ...
        2.7 / ...
        ( ...
        exp(-(Vr+55)/15) + ...
        exp((Vr+55)/15) ...
        );


    tao_h_t = ...
        ( ...
        30.8 + ...
        (211.4+exp((Vt+115.2)/5)) / ...
        (1+exp((Vt+86)/3.2)) ...
        ) / ...
        3.7371928;


    tao_h_r = ...
        ( ...
        85 + ...
        1 / ...
        ( ...
        exp((Vr+48)/4) + ...
        exp(-(Vr+407)/50) ...
        ) ...
        ) / ...
        3.7371928;


    m_limit_h = ...
        1/(1+exp((Vt+75)/5.5));


    tao_m_h = ...
        20 + ...
        1000 / ...
        ( ...
        exp((Vt+71.5)/14.2) + ...
        exp(-(Vt+89)/11.6) ...
        );


    Ph = ...
        k1*concentration_Ca^np / ...
        ( ...
        k1*concentration_Ca^np + ...
        k2 ...
        );


    R_pump = ...
        1.25 / ...
        (1+exp((20-concentration_O)/3)) ...
        / ...
        (1+exp((25-concentration_Na)/3)) ...
        / ...
        (1+exp(5.5-concentration_K));


    Na_pump = ...
        R_pump * ...
        ( ...
        concentration_Na^3 / ...
        (concentration_Na^3+3375) ...
        - ...
        Na0^3 / ...
        (Na0^3+3375) ...
        );


    %% New states

    Vp_new = ...
        Vp + ...
        dt * ...
        ( ...
        -J_L_p ...
        -JAMPA_Sep ...
        -JNMDA_Nep ...
        -JGABA_Sgp ...
        -Cm*taop*(I_M_p+I_Nap_p) ...
        ) / ...
        taop;


    Vi_new = ...
        Vi + ...
        dt * ...
        ( ...
        -J_L_i ...
        -JAMPA_Sei ...
        -JNMDA_Nei ...
        -JGABA_Sgi ...
        ) / ...
        taoi;


    Vt_new = ...
        Vt + ...
        dt * ...
        ( ...
        -J_L_t ...
        -JAMPA_Set ...
        -JGABA_Srt ...
        -Cm*taot*(I_LK_t+I_T_t+I_h) ...
        ) / ...
        taot;


    Vr_new = ...
        Vr + ...
        dt * ...
        ( ...
        -J_L_r ...
        -JAMPA_Ser ...
        -JGABA_Srr ...
        -Cm*taor*(I_LK_r+I_T_r) ...
        ) / ...
        taor;


    Sep_new = ...
        Sep + ...
        Sepdot*dt;


    Sepdot_new = ...
        Sepdot + ...
        dt*( ...
        gammae^2*(Npp*Qp+Npt*phit-Sep) ...
        -2*gammae*Sepdot ...
        ) ...
        + ...
        noise1(t-1);


    Sei_new = ...
        Sei + ...
        Seidot*dt;


    Seidot_new = ...
        Seidot + ...
        dt*( ...
        gammae^2*(Nip*Qp+Nit*phit-Sei) ...
        -2*gammae*Seidot ...
        ) ...
        + ...
        noise2(t-1);


    Set_new = ...
        Set + ...
        Setdot*dt;


    Setdot_new = ...
        Setdot + ...
        dt*( ...
        gammat^2*(Ntp*phip-Set) ...
        -2*gammat*Setdot ...
        ) ...
        + ...
        noise3(t-1);


    Ser_new = ...
        Ser + ...
        Serdot*dt;


    Serdot_new = ...
        Serdot + ...
        dt*( ...
        gammat^2*(Nrt*Qt+Nrp*phip-Ser) ...
        -2*gammat*Serdot ...
        );


    Nep_new = ...
        Nep + ...
        Nepdot*dt;


    Nepdot_new = ...
        Nepdot + ...
        dt*( ...
        gammane^2*(Npp*Qp-Nep) ...
        -2*gammane*Nepdot ...
        );


    Nei_new = ...
        Nei + ...
        Neidot*dt;


    Neidot_new = ...
        Neidot + ...
        dt*( ...
        gammane^2*(Nip*Qp-Nei) ...
        -2*gammane*Neidot ...
        );


    Sgp_new = ...
        Sgp + ...
        Sgpdot*dt;


    Sgpdot_new = ...
        Sgpdot + ...
        dt*( ...
        gammag^2*(Npi*Qi-Sgp) ...
        -2*gammag*Sgpdot ...
        );


    Sgi_new = ...
        Sgi + ...
        Sgidot*dt;


    Sgidot_new = ...
        Sgidot + ...
        dt*( ...
        gammag^2*(Nii*Qi-Sgi) ...
        -2*gammag*Sgidot ...
        );


    Srt_new = ...
        Srt + ...
        Srtdot*dt;


    Srtdot_new = ...
        Srtdot + ...
        dt*( ...
        gammar^2*(Ntr*Qr-Srt) ...
        -2*gammar*Srtdot ...
        );


    Srr_new = ...
        Srr + ...
        Srrdot*dt;


    Srrdot_new = ...
        Srrdot + ...
        dt*( ...
        gammar^2*(Nrr*Qr-Srr) ...
        -2*gammar*Srrdot ...
        );


    phip_new = ...
        phip + ...
        phipdot*dt;


    phipdot_new = ...
        phipdot + ...
        dt*( ...
        v^2*(Qp-phip) ...
        -2*v*phipdot ...
        );


    phit_new = ...
        phit + ...
        phitdot*dt;


    phitdot_new = ...
        phitdot + ...
        dt*( ...
        v^2*(Qt-phit) ...
        -2*v*phitdot ...
        );


    h_T_t_new = ...
        h_T_t + ...
        dt*( ...
        h_limit_t-h_T_t ...
        ) / ...
        tao_h_t;


    h_T_r_new = ...
        h_T_r + ...
        dt*( ...
        h_limit_r-h_T_r ...
        ) / ...
        tao_h_r;


    m_h1_new = ...
        m_h1 + ...
        dt*( ...
        ( ...
        m_limit_h*(1-m_h2)-m_h1 ...
        ) / ...
        tao_m_h ...
        - ...
        k3*Ph*m_h1 ...
        + ...
        k4*m_h2 ...
        );


    m_h2_new = ...
        m_h2 + ...
        dt*( ...
        k3*Ph*m_h1 ...
        - ...
        k4*m_h2 ...
        );


    zp_new = ...
        zp + ...
        dt*( ...
        zp_limit_t-zp ...
        ) / ...
        tao_z_t;


    zr_new = ...
        zr + ...
        dt*( ...
        zr_limit_t-zr ...
        ) / ...
        tao_z_t;


    j_new = ...
        j + ...
        dt*( ...
        j_limit ...
        - ...
        j/tao_j ...
        );


    concentration_Ca_new = ...
        concentration_Ca + ...
        dt*( ...
        alphaCa*I_T_t ...
        - ...
        (concentration_Ca-Ca0)/tao_Ca ...
        );


    concentration_Na_new = ...
        concentration_Na + ...
        dt*( ...
        alphaNa*Qp ...
        - ...
        Na_pump ...
        ) / ...
        tao_Na;


    concentration_K_new = ...
        concentration_K + ...
        dt*( ...
        0.3115*I_M_p ...
        - ...
        14*R_pump ...
        );


    concentration_O_new = ...
        concentration_O + ...
        dt*( ...
        -5.3*R_pump ...
        + ...
        0.17*(Obath-concentration_O) ...
        );


    I_cl = ...
        WGABA * ...
        Sgp * ...
        P_cl * ...
