%% =========================================================
% 18. LINEAR PSD CORRELATION
%% =========================================================

PSDcorr_linear = ...
    nan(nAnimals,1);

PSDcorr_linear_p = ...
    nan(nAnimals,1);


for ia = 1:nAnimals

    x = ...
        PSD_exp_interp(ia,:)';

    y = ...
        PSD_model_mean_linear(:);

    good = ...
        isfinite(x) & ...
        isfinite(y);


    if sum(good) >= 3

        [r,p] = ...
            corr( ...
            x(good), ...
            y(good), ...
            'Type','Pearson');


        PSDcorr_linear(ia) = r;

        PSDcorr_linear_p(ia) = p;

    end

end


%% =========================================================
% 19. RELATIVE-dB SPECTRAL-SHAPE CORRELATION
%% =========================================================

PSDcorr_dB = ...
    nan(nAnimals,1);

PSDcorr_dB_p = ...
    nan(nAnimals,1);


for ia = 1:nAnimals

    x = ...
        PSD_exp_all_rel_dB(ia,:)';

    y = ...
        PSD_model_mean_rel_dB(:);

    good = ...
        isfinite(x) & ...
        isfinite(y);


    if sum(good) >= 3

        [r,p] = ...
            corr( ...
            x(good), ...
            y(good), ...
            'Type','Pearson');


        PSDcorr_dB(ia) = r;

        PSDcorr_dB_p(ia) = p;

    end

end


