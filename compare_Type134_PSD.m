%% =========================================================
% 9. CORRELATION:
% EACH ANIMAL vs EACH MODEL PHENOTYPE
%% =========================================================

for ia = 1:nAnimals

    x = ...
        PSD_exp_dB(ia,:)';


    %% -----------------------------------------------------
    % Type 1
    %% -----------------------------------------------------

    y = ...
        PSD_Type1(:);

    good = ...
        isfinite(x) & ...
        isfinite(y);

    if sum(good) >= 3

        [r,p] = ...
            corr( ...
            x(good), ...
            y(good), ...
            'Type','Pearson');

        R(ia,1) = r;
        P(ia,1) = p;

    end


    %% -----------------------------------------------------
    % Type 3
    %% -----------------------------------------------------

    y = ...
        PSD_Type3(:);

    good = ...
        isfinite(x) & ...
        isfinite(y);

    if sum(good) >= 3

        [r,p] = ...
            corr( ...
            x(good), ...
            y(good), ...
            'Type','Pearson');

        R(ia,2) = r;
        P(ia,2) = p;

    end


    %% -----------------------------------------------------
    % Type 4
    %% -----------------------------------------------------

    y = ...
        PSD_Type4(:);

    good = ...
        isfinite(x) & ...
        isfinite(y);

    if sum(good) >= 3

        [r,p] = ...
            corr( ...
            x(good), ...
            y(good), ...
            'Type','Pearson');

        R(ia,3) = r;
        P(ia,3) = p;

    end

end


%% =========================================================
