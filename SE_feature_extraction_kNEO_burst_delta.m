clear;
clc;
close all;

%% =========================================================
% 1. Data path
%% =========================================================

dataFolder = ...
    'D:\Pilocarpine\Pilocarpine\Pilocarpine - GFP\Extracted_30s';

outFolder = fullfile( ...
    dataFolder, ...
    'Feature_results_kNEO');

if ~exist(outFolder,'dir')
    mkdir(outFolder);
end


%% =========================================================
% 2. Stages
%% =========================================================

stageList = {'onset','continuous'};


%% =========================================================
% 3. k-NEO detection parameters
%% =========================================================

fsDet = 256;          % Hz
kNEO = 3;
T_NEO = 1.8;

% Burst definition:
% Consecutive detected events separated by <= 0.5 s
% are grouped into the same burst.
% A valid burst contains at least 3 events.

burstGapSec = 0.5;
minEventsPerBurst = 3;


%% =========================================================
% 4. PSD parameters
%% =========================================================

fsPSD = 1000;           % Hz
freqRange = [1 30];     % Hz
fGrid = 1:0.1:30;

welchWindowSec = 4;      % s
welchOverlap = 0.5;      % 50%
nfft = 10000;


%% =========================================================
% 5. Save settings
%% =========================================================

DetectionSettings.fsDet = fsDet;
DetectionSettings.kNEO = kNEO;
DetectionSettings.threshold = T_NEO;
DetectionSettings.smoothingWindow = 4*kNEO + 1;
DetectionSettings.burstGapSec = burstGapSec;
DetectionSettings.minEventsPerBurst = minEventsPerBurst;

PSDSettings.fsPSD = fsPSD;
PSDSettings.freqRange = freqRange;
PSDSettings.fGrid = fGrid;
PSDSettings.welchWindowSec = welchWindowSec;
PSDSettings.welchOverlap = welchOverlap;
PSDSettings.nfft = nfft;


%% =========================================================
% 6. Analyze onset and continuous stages
%% =========================================================

for iStage = 1:length(stageList)

    stageName = stageList{iStage};

    fprintf('\n\n');
    fprintf('=============================================\n');
    fprintf('Processing stage: %s\n',stageName);
    fprintf('=============================================\n');


    %% -----------------------------------------------------
    % Find files
    %% -----------------------------------------------------

    files = dir( ...
        fullfile( ...
        dataFolder, ...
        ['*_' stageName '_30s.mat']));

    nAnimals = length(files);

    if nAnimals == 0

        warning( ...
            'No %s stage files were found.', ...
            stageName);

        continue;

    end

    fprintf('Found %d animals.\n',nAnimals);


    %% =====================================================
    % 7. Animal-level variables
    %% =====================================================

    Animal = strings(nAnimals,1);

    NChannelsUsed = nan(nAnimals,1);

    DischargeRate = nan(nAnimals,1);

    MedianIDI = nan(nAnimals,1);
    MeanIDI = nan(nAnimals,1);

    MedianBurstDuration = nan(nAnimals,1);

    % NEW:
    % Fraction of detected events belonging to valid bursts
    BurstEventFraction = nan(nAnimals,1);

    ActiveFraction = nan(nAnimals,1);

    DominantFreq = nan(nAnimals,1);

    DeltaRelativePower = nan(nAnimals,1);

    PSD_all = nan( ...
        nAnimals, ...
        length(fGrid));


    %% =====================================================
    % 8. Channel-level variables
    %% =====================================================

    ChannelAnimal = strings(0,1);
    ChannelLabel = strings(0,1);

    ChannelRate = [];

    ChannelMedianIDI = [];
    ChannelMeanIDI = [];

    ChannelBurstDuration = [];

    % NEW
    ChannelBurstEventFraction = [];

    ChannelActiveFraction = [];

    ChannelPeakFreq = [];

    ChannelDeltaRelativePower = [];

    ChannelNevents = [];


    %% =====================================================
    % 9. Loop over animals
    %% =====================================================

    for ia = 1:nAnimals

        fprintf('\n---------------------------------------------\n');
        fprintf('Processing: %s\n',files(ia).name);
        fprintf('---------------------------------------------\n');


        %% -------------------------------------------------
        % Load data
        %% -------------------------------------------------

        S = load( ...
            fullfile( ...
            files(ia).folder, ...
            files(ia).name));

        fieldNames = fieldnames(S);

        D = S.(fieldNames{1});

        Animal(ia) = string(D.animalID);

        signals = D.signals;

        fs_all = double(D.fs);

        labels = string(D.labels);

        nChannels = length(signals);

        fprintf('Animal: %s\n',Animal(ia));
        fprintf('Channels: %d\n',nChannels);


        %% -------------------------------------------------
        % Current-animal channel variables
        %% -------------------------------------------------

        rate_ch = nan(nChannels,1);

        medianIDI_ch = nan(nChannels,1);

        meanIDI_ch = nan(nChannels,1);

        medianBurstDuration_ch = nan(nChannels,1);

        % NEW
        burstEventFraction_ch = nan(nChannels,1);

        activeFraction_ch = nan(nChannels,1);

        peakFreq_ch = nan(nChannels,1);

        deltaRelativePower_ch = nan(nChannels,1);

        nEvents_ch = nan(nChannels,1);

        PSD_ch = nan( ...
            nChannels, ...
            length(fGrid));

        validChannel = false(nChannels,1);

        QCsaved = false;


        %% =================================================
        % 10. Loop over channels
        %% =================================================

        for ch = 1:nChannels

            x = signals{ch};

            if isempty(x)
                continue;
            end

            x = double(x(:));

            fsOriginal = fs_all(ch);


            %% ---------------------------------------------
            % Basic checking
            %% ---------------------------------------------

            if ~isfinite(fsOriginal) || ...
                    fsOriginal <= 0

                continue;

            end

            if any(~isfinite(x))
                continue;
            end

            if length(x) < 5*fsOriginal
                continue;
            end


            %% ---------------------------------------------
            % Exclude non-EEG channels
            %% ---------------------------------------------

            labelLower = lower(labels(ch));

            if contains(labelLower,'annotation') || ...
               contains(labelLower,'event') || ...
               contains(labelLower,'trigger')

                fprintf( ...
                    'Skip channel: %s\n', ...
                    labels(ch));

                continue;

            end


            %% =============================================
            % 11. Basic preprocessing
            %% =============================================

            x = detrend(x);

            x = x - mean(x);


            %% =============================================
            % 12. k-NEO discharge detection
            %% =============================================

            [ ...
                locs_det, ...
                x_det, ...
                time_det, ...
                neo_smooth ...
            ] = ...
                kneo_detect( ...
                    x, ...
                    fsOriginal, ...
                    fsDet, ...
                    kNEO, ...
                    T_NEO);


            %% ---------------------------------------------
            % 12.1 Number of discharge events
            %% ---------------------------------------------

            nEvents = length(locs_det);

            nEvents_ch(ch) = nEvents;


            %% ---------------------------------------------
            % 12.2 Discharge rate
            %% ---------------------------------------------

            durationSec = ...
                length(x_det)/fsDet;

            rate_ch(ch) = ...
                nEvents/durationSec;


            %% ---------------------------------------------
            % 12.3 Inter-event interval
            %% ---------------------------------------------

            if nEvents >= 2

                IEI = ...
                    diff(locs_det)/fsDet;

                medianIDI_ch(ch) = ...
                    median(IEI);

                meanIDI_ch(ch) = ...
                    mean(IEI);

            end


            %% ---------------------------------------------
            % 12.4 Burst features
            %
            % Events separated by <= burstGapSec are grouped
            % into the same burst.
            %
            % A valid burst must contain at least
            % minEventsPerBurst events.
            %% ---------------------------------------------

            eventTimes = ...
                locs_det/fsDet;


            if nEvents >= minEventsPerBurst

                eventGap = ...
                    diff(eventTimes);


                burstStartIdx = ...
                    [ ...
                    1; ...
                    find( ...
                    eventGap > burstGapSec) + 1 ...
                    ];


                burstEndIdx = ...
                    [ ...
                    find( ...
                    eventGap > burstGapSec); ...
                    nEvents ...
                    ];


                nEventsInBurst = ...
                    burstEndIdx ...
                    - burstStartIdx ...
                    + 1;


                validBurst = ...
                    nEventsInBurst >= ...
                    minEventsPerBurst;


                if any(validBurst)

                    burstStartTime = ...
                        eventTimes( ...
                        burstStartIdx( ...
                        validBurst));


                    burstEndTime = ...
                        eventTimes( ...
                        burstEndIdx( ...
                        validBurst));


                    burstDuration = ...
                        burstEndTime ...
                        - burstStartTime;


                    %% -------------------------------
                    % Median burst duration
                    %% -------------------------------

                    medianBurstDuration_ch(ch) = ...
                        median( ...
                        burstDuration);


                    %% -------------------------------
                    % NEW:
                    % Fraction of all detected events
                    % that belong to valid bursts
                    %% -------------------------------

                    nEventsInValidBursts = ...
                        sum( ...
                        nEventsInBurst( ...
                        validBurst));


                    burstEventFraction_ch(ch) = ...
                        nEventsInValidBursts / ...
                        nEvents;


                    %% -------------------------------
                    % Active fraction
                    %% -------------------------------

                    activeFraction_ch(ch) = ...
                        sum( ...
                        burstDuration) ...
                        / durationSec;


                else

                    activeFraction_ch(ch) = 0;

                    % Events exist, but none form
                    % a valid burst.
                    if nEvents > 0

                        burstEventFraction_ch(ch) = 0;

                    end

                end


            else

                activeFraction_ch(ch) = 0;

                % Fewer than minEventsPerBurst events:
                % no valid burst can be formed.
                if nEvents > 0

                    burstEventFraction_ch(ch) = 0;

                end

            end


            %% =============================================
            % 13. PSD analysis
            %% =============================================

            if abs(fsOriginal-fsPSD) > 1e-8

                [pPSD,qPSD] = ...
                    rat( ...
                    fsPSD/fsOriginal);

                x_psd = ...
                    resample( ...
                    x, ...
                    pPSD, ...
                    qPSD);

            else

                x_psd = x;

            end


            x_psd = ...
                x_psd ...
                - mean(x_psd);


            %% ---------------------------------------------
            % Welch PSD
            %% ---------------------------------------------

            winLength = ...
                round( ...
                welchWindowSec*fsPSD);


            overlapLength = ...
                round( ...
                welchOverlap*winLength);


            [Pxx,F] = ...
                pwelch( ...
                    x_psd, ...
                    hamming(winLength), ...
                    overlapLength, ...
                    nfft, ...
                    fsPSD);


            %% ---------------------------------------------
            % 1-30 Hz
            %% ---------------------------------------------

            idxFreq = ...
                F >= freqRange(1) & ...
                F <= freqRange(2);


            F_use = ...
                F(idxFreq);


            P_use = ...
                Pxx(idxFreq);


            %% ---------------------------------------------
            % Normalize PSD
            %% ---------------------------------------------

            totalPower = ...
                trapz( ...
                F_use, ...
                P_use);


            if totalPower <= 0 || ...
                    ~isfinite(totalPower)

                continue;

            end


            P_norm = ...
                P_use/totalPower;


            %% ---------------------------------------------
            % Delta relative power
            %% ---------------------------------------------

            idxDelta = ...
                F_use >= 1 & ...
                F_use <= 4;


            deltaRelativePower_ch(ch) = ...
                trapz( ...
                    F_use(idxDelta), ...
                    P_norm(idxDelta));


            %% ---------------------------------------------
            % Interpolate to common frequency grid
            %% ---------------------------------------------

            P_grid = ...
                interp1( ...
                    F_use, ...
                    P_norm, ...
                    fGrid, ...
                    'linear');


            PSD_ch(ch,:) = ...
                P_grid;


            %% ---------------------------------------------
            % Dominant frequency
            %% ---------------------------------------------

            [~,idxPeak] = ...
                max(P_norm);


            peakFreq_ch(ch) = ...
                F_use(idxPeak);


            validChannel(ch) = ...
                true;


            %% =============================================
            % 14. Save channel-level results
            %% =============================================

            ChannelAnimal(end+1,1) = ...
                Animal(ia);


            ChannelLabel(end+1,1) = ...
                labels(ch);


            ChannelNevents(end+1,1) = ...
                nEvents_ch(ch);


            ChannelRate(end+1,1) = ...
                rate_ch(ch);


            ChannelMedianIDI(end+1,1) = ...
                medianIDI_ch(ch);


            ChannelMeanIDI(end+1,1) = ...
                meanIDI_ch(ch);


            ChannelBurstDuration(end+1,1) = ...
                medianBurstDuration_ch(ch);


            % NEW
            ChannelBurstEventFraction(end+1,1) = ...
                burstEventFraction_ch(ch);


            ChannelActiveFraction(end+1,1) = ...
                activeFraction_ch(ch);


            ChannelPeakFreq(end+1,1) = ...
                peakFreq_ch(ch);


            ChannelDeltaRelativePower(end+1,1) = ...
                deltaRelativePower_ch(ch);


            %% =============================================
            % 15. Save QC data from first valid channel
            %% =============================================

            if ~QCsaved

                QC_x_det = ...
                    x_det;

                QC_time_det = ...
                    time_det;

                QC_locs = ...
                    locs_det;

                QC_neo = ...
                    neo_smooth;

                QC_label = ...
                    labels(ch);

                QC_PSD = ...
                    P_grid;

                QCsaved = ...
                    true;

            end

        end


        %% =================================================
        % 16. Animal-level feature aggregation
        %% =================================================

        idxValid = ...
            find(validChannel);


        NChannelsUsed(ia) = ...
            length(idxValid);


        if isempty(idxValid)

            warning( ...
                '%s has no valid EEG channels.', ...
                Animal(ia));

            continue;

        end


        %% ---------------------------------------------
        % Temporal features:
        % median across channels for each animal
        %% ---------------------------------------------

        DischargeRate(ia) = ...
            median( ...
                rate_ch(idxValid), ...
                'omitnan');


        MedianIDI(ia) = ...
            median( ...
                medianIDI_ch(idxValid), ...
                'omitnan');


        MeanIDI(ia) = ...
            median( ...
                meanIDI_ch(idxValid), ...
                'omitnan');


        MedianBurstDuration(ia) = ...
            median( ...
                medianBurstDuration_ch( ...
                idxValid), ...
                'omitnan');


        %% ---------------------------------------------
        % NEW:
        % Fraction of events occurring in valid bursts
        %% ---------------------------------------------

        BurstEventFraction(ia) = ...
            median( ...
                burstEventFraction_ch( ...
                idxValid), ...
                'omitnan');


        ActiveFraction(ia) = ...
            median( ...
                activeFraction_ch(idxValid), ...
                'omitnan');


        %% ---------------------------------------------
        % Animal-level mean PSD
        %% ---------------------------------------------

        PSD_animal = ...
            mean( ...
                PSD_ch(idxValid,:), ...
                1, ...
                'omitnan');


        areaAnimal = ...
            trapz( ...
                fGrid, ...
                PSD_animal);


        if areaAnimal > 0

            PSD_animal = ...
                PSD_animal/areaAnimal;

        end


        PSD_all(ia,:) = ...
            PSD_animal;


        %% ---------------------------------------------
        % Animal dominant frequency
        %% ---------------------------------------------

        [~,idxPeakAnimal] = ...
            max(PSD_animal);


        DominantFreq(ia) = ...
            fGrid(idxPeakAnimal);


        %% ---------------------------------------------
        % Animal delta relative power
        %% ---------------------------------------------

        idxDeltaGrid = ...
            fGrid >= 1 & ...
            fGrid <= 4;


        DeltaRelativePower(ia) = ...
            trapz( ...
                fGrid(idxDeltaGrid), ...
                PSD_animal(idxDeltaGrid));


        %% =================================================
        % 17. QC figure
        %% =================================================

        if QCsaved

            figure( ...
                'Visible','off', ...
                'Position', ...
                [100 100 900 850]);


            %% Panel 1: ECoG + detected events

            subplot(3,1,1);

            plot( ...
                QC_time_det, ...
                QC_x_det, ...
                'k', ...
                'LineWidth',0.7);

            hold on;


            if ~isempty(QC_locs)

                plot( ...
                    QC_time_det(QC_locs), ...
                    QC_x_det(QC_locs), ...
                    'ro', ...
                    'MarkerSize',4, ...
                    'LineWidth',1);

            end


            xlim([0 30]);

            xlabel('Time (s)');

            ylabel('Amplitude');

            title( ...
                sprintf( ...
                '%s - %s - %s', ...
                Animal(ia), ...
                stageName, ...
                QC_label));

            box off;


            %% Panel 2: k-NEO

            subplot(3,1,2);

            plot( ...
                QC_time_det, ...
                QC_neo, ...
                'k', ...
                'LineWidth',0.8);

            hold on;


            yline( ...
                T_NEO, ...
                '--r', ...
                sprintf( ...
                'T = %.1f', ...
                T_NEO));


            if ~isempty(QC_locs)

                plot( ...
                    QC_time_det(QC_locs), ...
                    QC_neo(QC_locs), ...
                    'ro', ...
                    'MarkerSize',4);

            end


            xlim([0 30]);

            xlabel('Time (s)');

            ylabel('k-NEO');

            box off;


            %% Panel 3: PSD

            subplot(3,1,3);

            plot( ...
                fGrid, ...
                PSD_animal, ...
                'k', ...
                'LineWidth',1.3);

            hold on;


            xline( ...
                DominantFreq(ia), ...
                '--');


            xlim([1 30]);

            xlabel('Frequency (Hz)');

            ylabel('Normalized PSD');

            box off;


            %% Save QC

            qcName = ...
                sprintf( ...
                '%s_%s_kNEO_QC.png', ...
                char(Animal(ia)), ...
                stageName);


            saveas( ...
                gcf, ...
                fullfile( ...
                    outFolder, ...
                    qcName));


            close(gcf);

        end


        %% =================================================
        % 18. Command-line output
        %% =================================================

        fprintf( ...
            'Channels used: %d\n', ...
            NChannelsUsed(ia));


        fprintf( ...
            'Discharge rate = %.3f events/s\n', ...
            DischargeRate(ia));


        fprintf( ...
            'Median inter-event interval = %.3f s\n', ...
            MedianIDI(ia));


        fprintf( ...
            'Median burst duration = %.3f s\n', ...
            MedianBurstDuration(ia));


        % NEW
        fprintf( ...
            'Events in bursts = %.3f (%.1f%%)\n', ...
            BurstEventFraction(ia), ...
            100*BurstEventFraction(ia));


        fprintf( ...
            'Active fraction = %.3f (%.1f%%)\n', ...
            ActiveFraction(ia), ...
            100*ActiveFraction(ia));


        fprintf( ...
            'Dominant frequency = %.2f Hz\n', ...
            DominantFreq(ia));


        fprintf( ...
            'Delta relative power (1-4 Hz) = %.3f\n', ...
            DeltaRelativePower(ia));

    end


    %% =====================================================
    % 19. Animal-level feature table
    %% =====================================================

    FeatureTable = ...
        table( ...
            Animal, ...
            NChannelsUsed, ...
            DischargeRate, ...
            MedianIDI, ...
            MeanIDI, ...
            MedianBurstDuration, ...
            BurstEventFraction, ...
            ActiveFraction, ...
            DominantFreq, ...
            DeltaRelativePower);


    disp(FeatureTable);


    featureFile = ...
        fullfile( ...
            outFolder, ...
            [ ...
            'Experimental_' ...
            stageName ...
            '_kNEO_features.csv' ...
            ]);


    writetable( ...
        FeatureTable, ...
        featureFile);


    %% =====================================================
    % 20. Channel-level feature table
    %% =====================================================

    ChannelFeatureTable = ...
        table( ...
            ChannelAnimal, ...
            ChannelLabel, ...
            ChannelNevents, ...
            ChannelRate, ...
            ChannelMedianIDI, ...
            ChannelMeanIDI, ...
            ChannelBurstDuration, ...
            ChannelBurstEventFraction, ...
            ChannelActiveFraction, ...
            ChannelPeakFreq, ...
            ChannelDeltaRelativePower, ...
            'VariableNames', ...
            { ...
            'Animal', ...
            'Channel', ...
            'Nevents', ...
            'DischargeRate', ...
            'MedianIDI', ...
            'MeanIDI', ...
            'MedianBurstDuration', ...
            'BurstEventFraction', ...
            'ActiveFraction', ...
            'DominantFreq', ...
            'DeltaRelativePower' ...
            });


    channelFile = ...
        fullfile( ...
            outFolder, ...
            [ ...
            'Experimental_' ...
            stageName ...
            '_kNEO_channel_features.csv' ...
            ]);


    writetable( ...
        ChannelFeatureTable, ...
        channelFile);


    %% =====================================================
    % 21. Group PSD
    %% =====================================================

    PSD_mean = ...
        mean( ...
            PSD_all, ...
            1, ...
            'omitnan');


    PSD_SD = ...
        std( ...
            PSD_all, ...
            0, ...
            1, ...
            'omitnan');


    psdFile = ...
        fullfile( ...
            outFolder, ...
            [ ...
            'Experimental_' ...
            stageName ...
            '_kNEO_PSD.mat' ...
            ]);


    save( ...
        psdFile, ...
        'fGrid', ...
        'PSD_all', ...
        'PSD_mean', ...
        'PSD_SD', ...
        'FeatureTable', ...
        'DetectionSettings', ...
        'PSDSettings');


    %% =====================================================
    % 22. Group statistics
    %% =====================================================

    fprintf('\n=============================================\n');

    fprintf( ...
        'Experimental %s stage summary\n', ...
        stageName);

    fprintf('=============================================\n');


    fprintf( ...
        'Discharge rate = %.3f +/- %.3f events/s\n', ...
        mean( ...
            DischargeRate, ...
            'omitnan'), ...
        std( ...
            DischargeRate, ...
            'omitnan'));


    fprintf( ...
        'Median inter-event interval = %.3f +/- %.3f s\n', ...
        mean( ...
            MedianIDI, ...
            'omitnan'), ...
        std( ...
            MedianIDI, ...
            'omitnan'));


    fprintf( ...
        'Median burst duration = %.3f +/- %.3f s\n', ...
        mean( ...
            MedianBurstDuration, ...
            'omitnan'), ...
        std( ...
            MedianBurstDuration, ...
            'omitnan'));


    %% NEW
    fprintf( ...
        'Events in bursts = %.3f +/- %.3f (fraction)\n', ...
        mean( ...
            BurstEventFraction, ...
            'omitnan'), ...
        std( ...
            BurstEventFraction, ...
            'omitnan'));


    fprintf( ...
        'Events in bursts = %.1f +/- %.1f %%\n', ...
        100*mean( ...
            BurstEventFraction, ...
            'omitnan'), ...
        100*std( ...
            BurstEventFraction, ...
            'omitnan'));


    fprintf( ...
        'Active fraction = %.3f +/- %.3f\n', ...
        mean( ...
            ActiveFraction, ...
            'omitnan'), ...
        std( ...
            ActiveFraction, ...
            'omitnan'));


    fprintf( ...
        'Dominant frequency = %.2f +/- %.2f Hz\n', ...
        mean( ...
            DominantFreq, ...
            'omitnan'), ...
        std( ...
            DominantFreq, ...
            'omitnan'));


    fprintf( ...
        'Delta relative power (1-4 Hz) = %.3f +/- %.3f\n', ...
        mean( ...
            DeltaRelativePower, ...
            'omitnan'), ...
        std( ...
            DeltaRelativePower, ...
            'omitnan'));


    %% =====================================================
    % 23. TEMPORAL FIGURES
        %% =====================================================
    % 23. TEMPORAL AND ADDITIONAL FEATURE FIGURES
    %
    % Five independent figures:
    %
    % 1) Discharge rate
    % 2) Median burst duration
    % 3) Events in bursts (%)
    % 4) Median inter-event interval
    % 5) Dominant frequency
    %% =====================================================


    %% -----------------------------------------------------
    % 23.1 Discharge rate
    %% -----------------------------------------------------

    validDR = ...
        isfinite(DischargeRate);

    figure( ...
        'Color','w', ...
        'Position',[200 200 430 420]);

    boxplot( ...
        DischargeRate(validDR), ...
        'Labels',{stageName});

    hold on;

    nValidDR = ...
        sum(validDR);

    if nValidDR > 0

        xj = ...
            1 + ...
            linspace( ...
                -0.08, ...
                 0.08, ...
                 nValidDR)';

        scatter( ...
            xj, ...
            DischargeRate(validDR), ...
            35, ...
            'filled');

    end

    ylabel( ...
        'Discharge rate (events/s)');

    title( ...
        sprintf( ...
        'Experimental %s: discharge rate', ...
        stageName));

    box off;

    set( ...
        gca, ...
        'LineWidth',1, ...
        'FontSize',11);

    figNameTemporal = ...
        fullfile( ...
            outFolder, ...
            [ ...
            'Experimental_' ...
            stageName ...
            '_DischargeRate.png' ...
            ]);

    saveas( ...
        gcf, ...
        figNameTemporal);


    %% -----------------------------------------------------
    % 23.2 Median burst duration
    %% -----------------------------------------------------

    validBD = ...
        isfinite(MedianBurstDuration);

    figure( ...
        'Color','w', ...
        'Position',[200 200 430 420]);

    boxplot( ...
        MedianBurstDuration(validBD), ...
        'Labels',{stageName});

    hold on;

    nValidBD = ...
        sum(validBD);

    if nValidBD > 0

        xj = ...
            1 + ...
            linspace( ...
                -0.08, ...
                 0.08, ...
                 nValidBD)';

        scatter( ...
            xj, ...
            MedianBurstDuration(validBD), ...
            35, ...
            'filled');

    end

    ylabel( ...
        'Median burst duration (s)');

    title( ...
        sprintf( ...
        'Experimental %s: median burst duration', ...
        stageName));

    box off;

    set( ...
        gca, ...
        'LineWidth',1, ...
        'FontSize',11);

    figNameTemporal = ...
