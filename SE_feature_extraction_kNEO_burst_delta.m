%% =========================================================
% Local function:
% k-point nonlinear energy operator detector
%% =========================================================

function [ ...
    locs_det, ...
    x_det, ...
    time_det, ...
    neo_smooth ...
    ] = ...
    kneo_detect( ...
        x, ...
        fsOriginal, ...
        fsDet, ...
        kNEO, ...
        threshold)


    %% -----------------------------------------------------
    % 1. Resample to 256 Hz
    %% -----------------------------------------------------

    if abs(fsOriginal-fsDet) > 1e-8

        [p,q] = ...
            rat( ...
            fsDet/fsOriginal);


        x_det = ...
            resample( ...
                x, ...
                p, ...
                q);

    else

        x_det = x;

    end


    x_det = ...
        double(x_det(:));


    %% -----------------------------------------------------
    % 2. Detrend and demean
    %% -----------------------------------------------------

    x_det = ...
        detrend(x_det);


    x_det = ...
        x_det ...
        - mean(x_det);


    %% -----------------------------------------------------
    % 3. Standardize
    %% -----------------------------------------------------

    sigma_x = ...
        std(x_det);


    if sigma_x <= 0 || ...
            ~isfinite(sigma_x)

        locs_det = [];

        neo_smooth = ...
            zeros( ...
            size(x_det));

        time_det = ...
            ( ...
            0:length(x_det)-1 ...
            )' / fsDet;

        return;

    end


    x_norm = ...
        x_det/sigma_x;


    %% -----------------------------------------------------
    % 4. k-point nonlinear energy operator
    %
    % psi[n] = x[n]^2 - x[n-k]*x[n+k]
    %% -----------------------------------------------------

    N = ...
        length(x_norm);


    neo = ...
        zeros(N,1);


    idx = ...
        (kNEO+1):(N-kNEO);


    neo(idx) = ...
        x_norm(idx).^2 ...
        - ...
        x_norm(idx-kNEO) .* ...
        x_norm(idx+kNEO);


    %% -----------------------------------------------------
    % 5. Hamming smoothing
    %% -----------------------------------------------------

    winLength = ...
        4*kNEO + 1;


    w = ...
        hamming(winLength);


    w = ...
        w/sum(w);


    neo_smooth = ...
        conv( ...
            neo, ...
            w, ...
            'same');


    %% -----------------------------------------------------
    % 6. Threshold detection
    %% -----------------------------------------------------

    mask = ...
        neo_smooth > threshold;


    dmask = ...
        diff( ...
        [ ...
        false; ...
        mask; ...
        false ...
        ]);


    eventStart = ...
        find( ...
        dmask == 1);


    eventEnd = ...
        find( ...
        dmask == -1) - 1;


    %% -----------------------------------------------------
    % 7. Keep one event per threshold-crossing region
    %% -----------------------------------------------------

    nEvents = ...
        length(eventStart);


    locs_det = ...
        zeros(nEvents,1);


    for ie = 1:nEvents

        currentRange = ...
            eventStart(ie): ...
            eventEnd(ie);


        [~,localMax] = ...
            max( ...
            neo_smooth( ...
            currentRange));


        locs_det(ie) = ...
            currentRange( ...
            localMax);

    end


    %% -----------------------------------------------------
    % 8. Time axis
    %% -----------------------------------------------------

    time_det = ...
        ( ...
        0:length(x_det)-1 ...
        )' / fsDet;

end